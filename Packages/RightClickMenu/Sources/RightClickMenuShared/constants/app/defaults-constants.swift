/// Fixed facts about what the app arrives with.
public enum DefaultsConstants {

    /// The name of the shipped legend file, without its extension.
    public static let builtInLegendResource = "built-in-legend"

    /// The extension of the shipped data files.
    public static let builtInLegendExtension = "json"

    /// The name of the shipped list of types the add screen offers.
    public static let knownTypesResource = "known-file-types"

    /// The extension a type falls back to when the add screen offers no choice.
    public static let fallbackExtension = "txt"
}
